CREATE TABLE students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    password_recovery_token_hash VARCHAR(64),
    password_recovery_expires_at TIMESTAMP WITHOUT TIME ZONE,
    password_recovery_window_started_at TIMESTAMP WITHOUT TIME ZONE,
    password_recovery_requests_in_window INTEGER,
    password_recovery_last_request_id VARCHAR(36),
    CONSTRAINT uk_students_email UNIQUE (email)
);

CREATE TABLE quiz_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject VARCHAR(50) NOT NULL,
    question_text VARCHAR(1000) NOT NULL,
    option_a VARCHAR(300) NOT NULL,
    option_b VARCHAR(300) NOT NULL,
    option_c VARCHAR(300) NOT NULL,
    option_d VARCHAR(300) NOT NULL,
    correct_answer VARCHAR(300) NOT NULL
);

CREATE TABLE exam_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL,
    subject VARCHAR(255) NOT NULL,
    score INTEGER NOT NULL,
    total_questions INTEGER NOT NULL,
    percentage INTEGER NOT NULL,
    exam_date TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    start_time TIMESTAMP WITHOUT TIME ZONE,
    completion_time TIMESTAMP WITHOUT TIME ZONE,
    duration_seconds BIGINT,
    published BOOLEAN,
    published_at TIMESTAMP WITHOUT TIME ZONE
);

CREATE TABLE exam_schedules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_name VARCHAR(255),
    subject VARCHAR(255),
    exam_date DATE,
    exam_time TIME WITHOUT TIME ZONE,
    description VARCHAR(2000),
    duration_minutes INTEGER NOT NULL,
    total_marks INTEGER NOT NULL
);

CREATE TABLE app_announcement_requests (
    request_id VARCHAR(36) PRIMARY KEY,
    request_fingerprint VARCHAR(64) NOT NULL,
    created_count INTEGER NOT NULL,
    announcement_title VARCHAR(120),
    announcement_message VARCHAR(1000),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE TABLE app_announcement_deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id VARCHAR(36) NOT NULL,
    student_id BIGINT NOT NULL,
    status VARCHAR(16) NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    last_attempt_at TIMESTAMP WITHOUT TIME ZONE,
    sent_at TIMESTAMP WITHOUT TIME ZONE,
    failure_reason VARCHAR(200),
    announcement_title VARCHAR(120),
    announcement_message VARCHAR(1000),
    CONSTRAINT uk_announcement_delivery_request_student
        UNIQUE (request_id, student_id),
    CONSTRAINT fk_announcement_delivery_request
        FOREIGN KEY (request_id)
        REFERENCES app_announcement_requests (request_id)
);

CREATE TABLE app_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_type VARCHAR(20) NOT NULL,
    recipient_id BIGINT NOT NULL,
    event_key VARCHAR(160) NOT NULL,
    title VARCHAR(120) NOT NULL,
    message VARCHAR(1000) NOT NULL,
    target_url VARCHAR(500) NOT NULL,
    notification_type VARCHAR(32),
    reference_id BIGINT,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    read_at TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT uk_app_notification_recipient_event
        UNIQUE (recipient_type, recipient_id, event_key)
);

CREATE INDEX idx_app_notification_recipient_created
    ON app_notifications (recipient_type, recipient_id, created_at);

CREATE TABLE exam_feedback (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_result_id BIGINT NOT NULL,
    student_id BIGINT NOT NULL,
    overall_rating INTEGER NOT NULL,
    difficulty_rating INTEGER NOT NULL,
    quality_rating INTEGER NOT NULL,
    experience_rating INTEGER NOT NULL,
    feedback_comment VARCHAR(1000),
    submitted_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT uk_exam_feedback_attempt UNIQUE (exam_result_id),
    CONSTRAINT fk_exam_feedback_exam_result
        FOREIGN KEY (exam_result_id) REFERENCES exam_results (id),
    CONSTRAINT fk_exam_feedback_student
        FOREIGN KEY (student_id) REFERENCES students (id)
);

CREATE TABLE exam_monitoring_attempts (
    attempt_id VARCHAR(36) PRIMARY KEY,
    student_id BIGINT NOT NULL,
    exam_identifier VARCHAR(120) NOT NULL,
    exam_subject VARCHAR(120),
    started_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    deadline TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    status VARCHAR(20) NOT NULL,
    warning_count INTEGER NOT NULL,
    disqualified_at TIMESTAMP WITH TIME ZONE,
    disqualification_reason VARCHAR(255),
    CONSTRAINT ck_monitor_attempt_warning_count
        CHECK (warning_count >= 0 AND warning_count <= 5)
);

CREATE INDEX idx_monitor_attempt_status_disqualified
    ON exam_monitoring_attempts (status, disqualified_at);

CREATE TABLE exam_monitoring_violations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL,
    exam_identifier VARCHAR(120) NOT NULL,
    exam_subject VARCHAR(120),
    attempt_id VARCHAR(36) NOT NULL,
    violation_type VARCHAR(32) NOT NULL,
    warning_number INTEGER NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    client_event_id VARCHAR(36) NOT NULL,
    CONSTRAINT uk_monitoring_client_event UNIQUE (client_event_id)
);

CREATE INDEX idx_monitoring_student_attempt
    ON exam_monitoring_violations (student_id, attempt_id);

CREATE TABLE scheduled_exam_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_schedule_id BIGINT NOT NULL,
    question_text VARCHAR(1000) NOT NULL,
    option_a VARCHAR(300) NOT NULL,
    option_b VARCHAR(300) NOT NULL,
    option_c VARCHAR(300) NOT NULL,
    option_d VARCHAR(300) NOT NULL,
    correct_answer VARCHAR(1) NOT NULL,
    CONSTRAINT fk_scheduled_exam_question_schedule
        FOREIGN KEY (exam_schedule_id) REFERENCES exam_schedules (id)
);

CREATE TABLE student_notification_preferences (
    student_id BIGINT PRIMARY KEY,
    exam_email_enabled BOOLEAN NOT NULL,
    result_email_enabled BOOLEAN NOT NULL,
    support_email_enabled BOOLEAN NOT NULL,
    announcement_email_enabled BOOLEAN NOT NULL,
    in_app_enabled BOOLEAN NOT NULL
);

CREATE TABLE support_conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL,
    subject VARCHAR(150) NOT NULL,
    category VARCHAR(32) NOT NULL,
    status VARCHAR(32) NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    last_message_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_support_conversation_student
        FOREIGN KEY (student_id) REFERENCES students (id)
);

CREATE TABLE support_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL,
    sender_type VARCHAR(16) NOT NULL,
    content VARCHAR(4000) NOT NULL,
    sent_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    read_by_student BOOLEAN NOT NULL,
    read_by_admin BOOLEAN NOT NULL,
    CONSTRAINT fk_support_message_conversation
        FOREIGN KEY (conversation_id) REFERENCES support_conversations (id)
);
